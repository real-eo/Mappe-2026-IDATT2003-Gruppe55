package edu.ntnu.idi.idatt2003.millions.model;

/**
 * Represents a player's progression level in the game.
 */
public enum PlayerStatus {
    /**
     * Starting level for players with limited progression.
     */
    NOVICE,
    /**
     * Mid-tier level earned through sustained growth and activity.
     */
    INVESTOR,
    /**
     * Top-tier level earned through high growth over many weeks.
     */
    SPECULATOR
}
